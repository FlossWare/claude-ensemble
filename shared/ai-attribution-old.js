// AI Attribution Formatting
// Creates consistent attribution format across ALL workflows
// Used by: code-review, pr-review, code-solve, code-improve
//
// Supports two patterns:
// 1. Arbiter-based: Models propose, arbiter chooses best (PR reviews)
// 2. Threshold-based: Models propose, confidence threshold filters (code review)

export function formatAIAttribution(reviews, arbiterDecision, options = {}) {
  const {
    includeVerboseDetails = true,
    includeTimestamp = true,
  } = options

  const { opus, sonnet, haiku, gemini } = reviews

  let attribution = `## 🤖 AI Attribution

**Multi-Model Consensus Review**

### Reviewer Models
- **Opus**: ${formatModelDecision(opus)}
- **Sonnet**: ${formatModelDecision(sonnet)}
- **Haiku**: ${formatModelDecision(haiku)}`

  if (gemini) {
    attribution += `\n- **Gemini**: ${formatModelDecision(gemini)}`
  }

  attribution += `

### Arbiter Decision
- **Final Decision**: ${arbiterDecision.final_decision}
- **Consensus Score**: ${arbiterDecision.consensus_score}% agreement
- **Best Analysis**: ${arbiterDecision.accepted_model}
- **Reasoning**: ${arbiterDecision.accepted_reasoning}
`

  if (arbiterDecision.rejected_models && arbiterDecision.rejected_models.length > 0) {
    attribution += `
### Rejected Models
${arbiterDecision.rejected_models.map(m =>
  `- **${m.model}**: ${m.rejection_reason}`
).join('\n')}
`
  }

  if (arbiterDecision.issue_priority) {
    attribution += `
### Priority
**${arbiterDecision.issue_priority}** - Validated by multi-model consensus
`
  }

  if (includeTimestamp) {
    attribution += `
---
*Generated by AI Multi-Model Review on ${new Date().toISOString().split('T')[0]}*
`
  }

  return attribution
}

export function formatModelDecision(modelReview) {
  if (!modelReview) return 'N/A'

  let decision = ''

  // Handle different schema types
  if (modelReview.is_real_issue !== undefined) {
    decision = modelReview.is_real_issue ? 'Real Issue' : 'False Positive'
  } else if (modelReview.approval_recommendation) {
    decision = modelReview.approval_recommendation === 'approve' ? 'Approve' :
              modelReview.approval_recommendation === 'request_changes' ? 'Request Changes' :
              'Comment'
  } else if (modelReview.approach) {
    decision = 'Fix Proposed'
  } else {
    decision = 'Reviewed'
  }

  const confidence = modelReview.confidence || 0
  return `${decision} (Confidence: ${confidence}%)`
}

export function formatShortAttribution(reviews, arbiterDecision) {
  const { opus, sonnet, haiku, gemini } = reviews
  const allModels = [opus, sonnet, haiku, gemini].filter(Boolean)

  const agreeCount = allModels.filter(m => {
    if (arbiterDecision.final_decision === 'real_issue' || arbiterDecision.final_decision === 'approved') {
      return m.is_real_issue === true || m.approval_recommendation === 'approve'
    } else {
      return m.is_real_issue === false || m.approval_recommendation !== 'approve'
    }
  }).length

  return `🤖 **AI Review**: ${agreeCount}/${allModels.length} models agree | Consensus: ${arbiterDecision.consensus_score}% | Best: ${arbiterDecision.accepted_model}`
}

export function formatInlineComment(issue, reviews, arbiterDecision) {
  return `## 🤖 AI Code Review

**Issue**: ${issue.description}

${formatShortAttribution(reviews, arbiterDecision)}

**Models Detected This**:
${Object.entries(reviews).filter(([_, v]) => v).map(([model, review]) =>
  `- ${model.charAt(0).toUpperCase() + model.slice(1)}: ${review.confidence || 0}% confidence`
).join('\n')}

**Arbiter Verdict**: ${arbiterDecision.final_decision}

---
*Multi-model AI code review - ${arbiterDecision.consensus_score}% consensus*
`
}

export function formatPRComment(reviews, arbiterDecision, qualityScore) {
  const { opus, sonnet, haiku, gemini } = reviews

  return `## 🤖 AI Pull Request Review

### Quality Score: ${qualityScore}/100

### Multi-Model Consensus
${formatShortAttribution(reviews, arbiterDecision)}

### Detailed Reviews

**Opus** (${opus?.confidence || 0}% confidence):
- Recommendation: ${opus?.approval_recommendation || 'N/A'}
- Issues Found: ${opus?.issues_found?.length || 0}
${opus?.strengths ? `- Strengths: ${opus.strengths.slice(0, 2).join(', ')}` : ''}

**Sonnet** (${sonnet?.confidence || 0}% confidence):
- Recommendation: ${sonnet?.approval_recommendation || 'N/A'}
- Issues Found: ${sonnet?.issues_found?.length || 0}

**Haiku** (${haiku?.confidence || 0}% confidence):
- Recommendation: ${haiku?.approval_recommendation || 'N/A'}
- Issues Found: ${haiku?.issues_found?.length || 0}

${gemini ? `**Gemini** (${gemini?.confidence || 0}% confidence):
- Recommendation: ${gemini?.approval_recommendation || 'N/A'}
- Issues Found: ${gemini?.issues_found?.length || 0}
` : ''}

### Arbiter Decision
**${arbiterDecision.final_decision.toUpperCase()}** (${arbiterDecision.consensus_score}% consensus)

**Reasoning**: ${arbiterDecision.accepted_reasoning}

---
*AI-powered PR review - Multi-model consensus*
`
}

/**
 * Enhanced PR comment with full AI transparency
 * Shows: arbiter reasoning, all worker reviews + suggestions, rejection reasons
 */
export function formatPRCommentEnhanced(reviews, arbiterDecision, qualityScore, options = {}) {
  const { showFullReviews = true, showRejectionReasons = true } = options
  const { opus, sonnet, haiku, gemini } = reviews
  const allReviews = { opus, sonnet, haiku, gemini }

  // Determine accepted and rejected models
  const acceptedModel = arbiterDecision.accepted_model || 'unknown'
  const acceptedReview = allReviews[acceptedModel.toLowerCase()]

  let md = `## 🤖 AI Pull Request Review\n\n`
  md += `### Quality Score: ${qualityScore}/100\n\n`

  // ARBITER SECTION
  md += `---\n\n`
  md += `### ⚖️ Arbiter AI Decision\n\n`
  md += `**Arbiter Model**: ${arbiterDecision.arbiter_model || 'consensus-engine'}\n`
  md += `**Final Decision**: **${arbiterDecision.final_decision.toUpperCase()}**\n`
  md += `**Consensus Score**: ${arbiterDecision.consensus_score}%\n\n`

  md += `**✅ Why Accepted ${acceptedModel}:**\n`
  md += `${arbiterDecision.accepted_reasoning || 'Best overall analysis and recommendations'}\n\n`

  if (showRejectionReasons && arbiterDecision.rejected_models?.length > 0) {
    md += `**❌ Why Rejected Others:**\n`
    arbiterDecision.rejected_models.forEach(rejected => {
      md += `- **${rejected.model}**: ${rejected.rejection_reason}\n`
    })
    md += `\n`
  }

  // ACCEPTED REVIEW
  md += `---\n\n`
  md += `### ✅ Accepted Review\n\n`
  md += `**Model**: ${acceptedModel}\n`
  md += `**Confidence**: ${acceptedReview?.confidence || 0}%\n`
  md += `**Recommendation**: ${acceptedReview?.approval_recommendation || 'N/A'}\n`
  md += `**Issues Found**: ${acceptedReview?.issues_found?.length || 0}\n\n`

  if (showFullReviews && acceptedReview) {
    if (acceptedReview.strengths?.length > 0) {
      md += `**Strengths:**\n`
      acceptedReview.strengths.forEach(s => md += `- ${s}\n`)
      md += `\n`
    }

    if (acceptedReview.issues_found?.length > 0) {
      md += `**Issues:**\n`
      acceptedReview.issues_found.slice(0, 5).forEach((issue, idx) => {
        md += `${idx + 1}. ${issue.description || issue}\n`
      })
      if (acceptedReview.issues_found.length > 5) {
        md += `   *(+${acceptedReview.issues_found.length - 5} more issues)*\n`
      }
      md += `\n`
    }

    if (acceptedReview.suggestions?.length > 0) {
      md += `**Suggestions:**\n`
      acceptedReview.suggestions.slice(0, 3).forEach(s => md += `- ${s}\n`)
      md += `\n`
    }
  }

  // REJECTED REVIEWS
  const rejectedModels = Object.entries(allReviews).filter(([model, _]) =>
    model.toLowerCase() !== acceptedModel.toLowerCase() && allReviews[model]
  )

  if (rejectedModels.length > 0) {
    md += `---\n\n`
    md += `### ❌ Alternative Reviews (${rejectedModels.length})\n\n`

    rejectedModels.forEach(([model, review], idx) => {
      const rejectionInfo = arbiterDecision.rejected_models?.find(r =>
        r.model.toLowerCase() === model.toLowerCase()
      )

      md += `#### ${idx + 1}. ${model.charAt(0).toUpperCase() + model.slice(1)}\n\n`
      md += `**Confidence**: ${review?.confidence || 0}%\n`
      md += `**Recommendation**: ${review?.approval_recommendation || 'N/A'}\n`
      md += `**Issues Found**: ${review?.issues_found?.length || 0}\n`

      if (showRejectionReasons && rejectionInfo) {
        md += `**Why Not Selected**: ${rejectionInfo.rejection_reason}\n`
      }

      if (showFullReviews && review?.issues_found?.length > 0) {
        md += `\n<details>\n<summary>View Issues (${review.issues_found.length})</summary>\n\n`
        review.issues_found.slice(0, 3).forEach((issue, i) => {
          md += `${i + 1}. ${issue.description || issue}\n`
        })
        if (review.issues_found.length > 3) {
          md += `   *(+${review.issues_found.length - 3} more)*\n`
        }
        md += `\n</details>\n`
      }

      md += `\n`
    })
  }

  // STATISTICS
  md += `---\n\n`
  md += `### 📊 Review Statistics\n\n`
  md += `- **Total Reviewers**: ${Object.values(allReviews).filter(Boolean).length}\n`
  md += `- **Consensus**: ${arbiterDecision.consensus_score}%\n`
  md += `- **Quality Score**: ${qualityScore}/100\n`
  md += `- **Decision**: ${arbiterDecision.final_decision.toUpperCase()}\n`
  md += `- **Arbiter**: ${arbiterDecision.arbiter_model || 'consensus-engine'}\n\n`

  md += `---\n`
  md += `*🤖 AI-powered PR review with full transparency - Multi-model consensus*\n`

  return md
}

